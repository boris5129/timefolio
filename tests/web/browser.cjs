const assert = require('node:assert/strict')
const { join } = require('node:path')
const { chromium } = require('playwright')
const baseURL = process.env.TIMEFOLIO_TEST_URL || 'http://127.0.0.1:4173'

async function run() {
  const browser = await chromium.launch({ channel: 'msedge' })
  try {
    const page = await browser.newPage({ viewport: { width: 1366, height: 850 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', entry => { if (entry.type() === 'error') errors.push(entry.text()) })
    await page.goto(baseURL)
    await page.getByRole('heading', { name: '대시보드', exact: true }).waitFor()
    await page.getByText('아직 기록된 활동이 없어요').waitFor()
    assert.equal(await page.locator('#dash-unrecorded').textContent(), '24시간')
    const nav = page.getByRole('navigation')
    const register = () => nav.getByRole('button', { name: '활동 등록' }).click()
    const day = () => nav.getByRole('button', { name: '오늘의 활동' }).click()
    await register()
    await page.getByRole('button', { name: '10:00에 등록' }).click()
    assert.match(await page.getByLabel('시작 시각', { exact: true }).inputValue(), /T10:00$/)
    assert.match(await page.getByLabel('종료 시각', { exact: true }).inputValue(), /T11:00$/)
    await page.getByLabel('활동 이름').fill('독서')
    await page.getByRole('button', { name: '저장', exact: true }).click()
    await day()
    await page.getByRole('button', { name: '독서', exact: true }).click()
    await page.getByLabel('활동 이름').fill('저녁 독서')
    await page.getByRole('button', { name: '저장', exact: true }).click()
    await page.reload()
    await page.getByRole('button', { name: '저녁 독서 수정' }).waitFor()
    assert.equal(await page.locator('#summary article').first().locator('strong').textContent(), '1시간')
    await page.getByRole('button', { name: '목표 설정', exact: true }).click()
    await page.getByRole('button', { name: '수면 수정' }).click()
    await page.getByLabel('하루 목표 (분)').fill('45')
    await page.getByRole('button', { name: '저장', exact: true }).click()
    await day()
    const budget = page.getByRole('region', { name: '카테고리별 시간 예산' })
    await budget.getByText('15분 초과', { exact: true }).waitFor()
    const meter = budget.getByRole('progressbar', { name: '수면 시간 예산' })
    assert.equal(await meter.getAttribute('max'), '45')
    assert.equal(await meter.getAttribute('value'), '45')
    await register()
    await page.getByRole('button', { name: '다음 날짜' }).click()
    await page.getByRole('button', { name: '전날 활동 복사' }).click()
    await page.getByText('1개 활동을 계획으로 복사했습니다.').waitFor()
    await day()
    await page.getByRole('button', { name: '저녁 독서 삭제' }).click()
    await page.getByRole('dialog', { name: '삭제 확인' }).getByRole('button', { name: '삭제' }).click()
    await page.getByText('아직 기록된 활동이 없어요').waitFor()
    await register()
    await page.getByRole('radio', { name: '계획', exact: true }).check()
    await page.getByRole('button', { name: '09:00에 등록' }).click()
    await page.getByRole('dialog', { name: '계획 추가' }).waitFor()
    await page.getByLabel('활동 이름').fill('개별 계획')
    await page.getByRole('button', { name: '저장', exact: true }).click()
    await page.getByText('저장했습니다.', { exact: true }).waitFor()
    await page.getByRole('button', { name: /반복 저장/ }).click()
    const repeat = page.getByRole('dialog', { name: '활동 반복 저장' })
    await repeat.getByLabel('활동 이름').nth(0).fill('수업')
    await repeat.getByLabel('활동 이름').nth(1).fill('쉬는 시간')
    await repeat.getByRole('button', { name: '반복 저장', exact: true }).click()
    await page.getByText('8개 활동을 저장했습니다.').waitFor()
    await page.reload()
    await day()
    await page.getByRole('button', { name: '다음 날짜' }).click()
    assert.equal(await page.getByRole('button', { name: '수업 수정' }).count(), 4)
    assert.equal(await page.getByRole('button', { name: '쉬는 시간 수정' }).count(), 4)
    assert.equal(await page.locator('#summary article').nth(1).locator('strong').textContent(), '4시간')
    await page.getByRole('img', { name: /24시간 생활계획표.*안쪽 계획 4시간/ }).waitFor()
    assert.match(await page.locator('#clock-planned').evaluate(node => node.style.backgroundImage), /conic-gradient/)
    if (process.env.TIMEFOLIO_QA_IMAGE) await page.screenshot({ path: process.env.TIMEFOLIO_QA_IMAGE, fullPage: true })

    await page.getByRole('button', { name: '아낀 시간 기록' }).click()
    await page.getByLabel('아낀 시간 (분)').fill('30')
    await page.getByLabel('어떻게 아꼈나요?').fill('이동 시간 단축')
    await page.getByRole('button', { name: '저장', exact: true }).click()
    assert.equal(await page.locator('#saving-value').textContent(), '30분')
    await nav.getByRole('button', { name: '시간 확보' }).click()
    await page.getByRole('region', { name: '최근 절약 기록' }).getByText('이동 시간 단축').waitFor()
    await nav.getByRole('button', { name: '주간 활동' }).click()
    await page.locator('#period-totals').getByText('30분').waitFor()
    assert.equal(await page.locator('.calendar-day').count(), 7)
    await nav.getByRole('button', { name: '월간 활동' }).click()
    await page.locator('#period-totals').getByText('30분').waitFor()
    const savedCell = page.getByRole('button', { name: /아낀 시간 30분/ })
    await savedCell.click()
    await page.getByRole('button', { name: '활동 선택', exact: true }).click()
    await page.getByRole('checkbox', { name: '개별 계획 선택' }).check()
    await page.getByRole('button', { name: '선택 삭제 (1)' }).click()
    await page.getByRole('dialog', { name: '삭제 확인' }).getByRole('button', { name: '삭제', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: '개별 계획 수정' }).count(), 0)
    assert.equal(await page.getByRole('button', { name: '수업 수정' }).count(), 4)
    await page.getByRole('button', { name: '이 날짜 전체 삭제' }).click()
    await page.getByRole('dialog', { name: '삭제 확인' }).getByRole('button', { name: '삭제', exact: true }).click()
    await page.getByText('아직 기록된 활동이 없어요').waitFor()
    assert.equal(await page.locator('#saving-value').textContent(), '30분')
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: '카테고리', exact: true }).click()
    await page.getByRole('button', { name: /카테고리 추가/ }).click()
    await page.getByLabel('카테고리 이름').fill('산책')
    await page.getByRole('button', { name: '저장', exact: true }).click()
    await page.getByRole('button', { name: '산책 수정' }).click()
    await page.getByLabel('카테고리 이름').fill('동네 산책')
    await page.getByRole('button', { name: '저장', exact: true }).click()
    await page.getByRole('button', { name: '동네 산책 삭제' }).click()
    await page.getByRole('dialog', { name: '삭제 확인' }).getByRole('button', { name: '삭제' }).click()
    await page.getByRole('button', { name: '동네 산책 삭제' }).waitFor({ state: 'detached' })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390)
    await nav.getByRole('button', { name: '월간 활동' }).click()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390)
    await day()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390)
    await register()
    await page.getByLabel('조회 날짜', { exact: true }).fill('2026-11-23')
    await page.getByRole('button', { name: /반복 저장/ }).click()
    const schedule = page.getByRole('dialog', { name: '활동 반복 저장' })
    await schedule.getByLabel('반복 주기').selectOption('weekly')
    for (const weekday of ['월', '수', '금']) await schedule.getByRole('checkbox', { name: weekday, exact: true }).check()
    await schedule.getByLabel('반복 종료 날짜').fill('2026-11-29')
    await schedule.getByLabel('활동 이름').nth(0).fill('반복 수업')
    await schedule.getByLabel('활동 이름').nth(1).fill('반복 쉬는 시간')
    await schedule.getByRole('button', { name: '반복 저장', exact: true }).click()
    await page.getByText('3일에 계획 24개를 저장했습니다.', { exact: true }).waitFor()
    await nav.getByRole('button', { name: '주간 활동' }).click()
    await page.getByRole('button', { name: /2026-11-25 .*계획 4시간/ }).click()
    assert.equal(await page.getByRole('button', { name: '반복 수업 수정' }).count(), 4)
    await register()
    const pickDate = value => page.getByLabel('조회 날짜', { exact: true }).fill(value)
    await pickDate('2026-12-24')
    await page.getByRole('button', { name: /반복 저장/ }).click()
    await schedule.getByLabel('반복 주기').selectOption('daily')
    await schedule.getByLabel('무기한 반복').check()
    await schedule.getByLabel('한국 공휴일 제외').check()
    assert.equal(await schedule.getByLabel('반복 종료 날짜').isVisible(), false)
    await schedule.getByLabel('활동 이름').nth(0).fill('무기한 수업')
    await schedule.getByLabel('활동 이름').nth(1).fill('무기한 휴식')
    await schedule.getByRole('button', { name: '반복 저장', exact: true }).click()
    await page.getByText('무기한 반복을 저장했습니다.', { exact: true }).waitFor()
    await page.reload()
    await day()
    await pickDate('2026-12-25')
    await page.getByText('아직 기록된 활동이 없어요').waitFor()
    await pickDate('2026-12-26')
    assert.equal(await page.getByRole('button', { name: '무기한 수업 수정' }).count(), 4)
    await register()
    await page.getByRole('button', { name: /무기한 수업.*반복 중단/ }).click()
    await page.getByRole('dialog', { name: '반복 중단 확인' }).getByRole('button', { name: '중단', exact: true }).click()
    await day()
    await page.getByText('아직 기록된 활동이 없어요').waitFor()
    await page.goto(baseURL + '/#home')
    const home = page.getByRole('heading', { name: '대시보드', exact: true })
    await home.waitFor()
    assert.equal(await page.locator('#dash-used').textContent(), '1시간')
    await nav.getByRole('button', { name: '설정' }).click()
    await page.getByRole('button', { name: '시간 중첩', exact: true }).click()
    await page.getByRole('heading', { name: '활동 중첩과 절약' }).waitFor()
    await page.goto(baseURL + '/#statistics')
    await page.getByRole('button', { name: '주간 결산' }).click()
    assert.equal(await page.locator('.calendar-day').count(), 7)
    if (process.env.TIMEFOLIO_REDESIGN_QA) {
      const screens = ['home', 'day', 'register', 'week', 'month', 'saved', 'categories', 'settings',
        'stack', 'invest', 'wish', 'goals', 'simulate', 'statistics', 'account']
      for (const [width, height] of [[1366, 900], [390, 844]]) {
        await page.setViewportSize({ width, height })
        for (const screen of screens) {
          await page.goto(baseURL + '/#' + screen)
          await page.locator('main[data-view="' + screen + '"]').waitFor()
          assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), width)
          await page.screenshot({ path: join(process.env.TIMEFOLIO_REDESIGN_QA, width + '-' + screen + '.png'), fullPage: true, animations: 'disabled' })
        }
      }
      await page.goto(baseURL + '/#register')
      await page.getByRole('button', { name: /반복 저장/ }).click()
      await page.screenshot({ path: join(process.env.TIMEFOLIO_REDESIGN_QA, '390-repeat-dialog.png'), animations: 'disabled' })
    }
    await page.evaluate(() => {
      const key = 'timefolio.ledger.v1'
      const data = JSON.parse(localStorage.getItem(key))
      const date = '2026-11-22'
      for (const [title, categoryId, start, end, kind] of [
        ['이동', 'default-3', '09:00', '10:00', 'actual'],
        ['출근길 독서', 'default-2', '09:00', '09:30', 'actual'],
        ['출근길 독서', 'default-2', '13:00', '13:30', 'planned'],
        ['쉬기', 'default-11', '14:00', '15:00', 'planned'],
        ['쉬기', 'default-11', '14:00', '15:00', 'actual'],
        ['게임', 'default-7', '16:00', '16:30', 'planned'],
        ['게임', 'default-7', '16:00', '17:00', 'actual'],
      ]) data.entries.push({ id: crypto.randomUUID(), title, categoryId, start: date + 'T' + start, end: date + 'T' + end, kind, memo: '' })
      localStorage.setItem(key, JSON.stringify(data))
    })
    await page.reload()
    await day()
    await pickDate('2026-11-22')
    assert.equal(await page.locator('#overlap-total').textContent(), '30분')
    assert.equal(await page.locator('#overlap-confirmed').textContent(), '0분')
    await page.getByRole('button', { name: '대체 확인', exact: true }).click()
    assert.equal(await page.locator('#overlap-confirmed').textContent(), '30분')
    const review = page.getByRole('region', { name: '하루 돌아보기' })
    await review.getByText(/75%/).waitFor()
    await review.getByText(/쉴 시간을 챙겼어요/).waitFor()
    await review.getByText(/계획보다 30분 더 썼어요/).waitFor()
    await pickDate('2026-12-25')
    await nav.getByRole('button', { name: '월간 활동' }).click()
    await page.getByRole('button', { name: /2026-12-25 .*공휴일/ }).getByText('공휴일', { exact: true }).waitFor()
    assert.match(await page.getByRole('button', { name: /2026-12-26 .*토요일/ }).getAttribute('class'), /saturday/)
    assert.deepEqual(errors, [])
    console.log('Edge 브라우저 PC·모바일 검증 통과')
  } finally {
    await browser.close()
  }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
